"""P21a — does each system's data honour the event specification it is given?

WHY THIS EXISTS
---------------
The benchmark specifies one uniform rule for where a trajectory ends:

    the event is  A(t) = f * A(0),  reached by log-interpolation in time,
    and everything after the crossing is discarded

with `f` given per system (1e3 for `rd` and `sidm`, 1e2 for `ks` and `film`,
3 for `burgers`). That rule is what a third party regenerating the benchmark
from `STATECOND_BENCHMARK.md` would implement, and it is what makes `phi` run
over the same interval `[0, log10 f]` in every trajectory of a system.

For the four testbeds the rule is exact. For `sidm` it is not, and nothing
checked. `sidm` is not generated by the benchmark harness: it is imported from
the gravothermal training set, where

  * `t_sing` is the SOLVER's termination time -- whichever of the density
    criterion (`rho[3] >= 1e3 rho[3](0)`, status 0, 40% of the retained runs)
    and the Knudsen floor (`Kn <= kn_min`, status 2, the other 60%) fires
    first; and
  * `A` is the density at the innermost point of the 128-point STORAGE grid,
    which is a different radius from the solver's shell 3.

Two different radii and two different criteria, so `A(t_sing)/A(0)` is not `f`
and is not even constant. This script measures it, and the acceptance gate
`test_event_specification_holds` fails any system whose data does not honour
its own stated rule.

Output: results/statecond/event_spec.json
"""
import json
import os
import sys

import numpy as np

ROOT = os.path.join(os.path.dirname(__file__), '..')
sys.path.insert(0, os.path.join(ROOT, 'src'))
sys.path.insert(0, os.path.dirname(__file__))

import statecond.data as scd                                     # noqa: E402
from sc_provenance import stamp                                  # noqa: E402

OUT = os.path.join(ROOT, 'results', 'statecond')
DATA = os.path.join(ROOT, 'data', 'sc')

# the `f` of the specification table, per system
# `f` for the four generated testbeds. `sidm` is deliberately absent: after the
# 2026-09-06 decision it is NOT specified by a threshold at all (see
# `sidm_termination_split` below and STATECOND_BENCHMARK.md).
SPEC_F = {'rd': 1e3, 'ks': 1e2, 'film': 1e2, 'burgers': 3.0}
SIDM_NOMINAL_F = 1e3   # what the old specification claimed, kept to measure it
TOL = 0.01          # 1% -- the rule is a threshold crossing, so it is exact


def sidm_termination_split(src=None):
    """How `sidm` runs actually end, counted rather than asserted.

    The re-specified rule is "solver termination, whichever of the density
    criterion and the Knudsen fluid-validity floor fires first". That is only
    honest if the split is reported, because it decides how much of the system
    is a gravothermal singularity at all: status 0 is the density criterion,
    status 2 is the Knudsen floor, and status 1 (neither) is dropped at import.
    """
    import h5py
    src = src or os.path.join(ROOT, 'data', 'd1', 'train.h5')
    if not os.path.exists(src):
        return None
    with h5py.File(src, 'r') as f:
        st = f['status'][:]
    kept = st != 1
    n = int(kept.sum())
    n0 = int((st == 0).sum())
    n2 = int((st == 2).sum())
    return {
        'source': os.path.relpath(src, ROOT),
        'n_total': int(st.size),
        'n_dropped_status1_no_termination': int((st == 1).sum()),
        'n_kept': n,
        'n_density_criterion_status0': n0,
        'n_knudsen_floor_status2': n2,
        'frac_density_criterion': n0 / n if n else None,
        'frac_knudsen_floor': n2 / n if n else None,
        'note': ('the density criterion is rho[3] >= 1e3 rho[3](0) and the '
                 'Knudsen floor is Kn <= kn_min = 0.02, both evaluated at '
                 'shell INDEX 3, which encloses a different mass fraction on '
                 'every grid -- so t_sing carries a grid-dependent definition '
                 'and a convergence study on it would mix discretisation with '
                 'a change of definition'),
    }


def main():
    out = {}
    for name, f in dict(SPEC_F, sidm=SIDM_NOMINAL_F).items():
        p = os.path.join(DATA, f'{name}.h5')
        if not os.path.exists(p):
            continue
        d = scd.load(p)
        a = np.asarray(d['a'], dtype=np.float64)
        ratio = a[:, -1] / a[:, 0]
        rel = np.abs(ratio - f) / f
        out[name] = {
            'specified_f': f,
            'n_runs': int(len(ratio)),
            'ratio_median': float(np.median(ratio)),
            'ratio_min': float(ratio.min()),
            'ratio_max': float(ratio.max()),
            'ratio_p5': float(np.percentile(ratio, 5)),
            'ratio_p95': float(np.percentile(ratio, 95)),
            'max_rel_deviation_from_f': float(rel.max()),
            'frac_within_1pct_of_f': float((rel <= TOL).mean()),
            'honours_specification': bool(rel.max() <= TOL),
            # phi's endpoint: constant log10(f) if the rule holds, else a range
            'phi_endpoint_dex_min': float(np.log10(ratio.min())),
            'phi_endpoint_dex_max': float(np.log10(ratio.max())),
            'phi_endpoint_spread_dex': float(np.log10(ratio.max())
                                             - np.log10(ratio.min())),
        }
    if 'sidm' in out:
        # sidm is no longer held to a threshold; it is measured against the
        # nominal one only to keep the size of the old claim on the record
        out['sidm']['specification'] = (
            'solver termination, whichever of the density criterion and the '
            'Knudsen fluid-validity floor fires first (re-specified '
            '2026-09-06); the 1e3 shown is the RETIRED nominal threshold, '
            'reported to keep the size of the discrepancy on the record')
        out['sidm']['is_reference_system'] = False
        out['sidm']['termination_split'] = sidm_termination_split()
    bad = [k for k, v in out.items()
           if k in SPEC_F and not v['honours_specification']]
    sp = out.get('sidm', {}).get('termination_split') or {}
    out['_summary'] = {
        'reference_systems': sorted(SPEC_F),
        'application_systems': ['sidm'],
        'honoured_by': sorted(k for k in SPEC_F if k in out
                              and out[k]['honours_specification']),
        'violated_by': sorted(bad),
        'sidm_note': (
            'sidm is an APPLICATION system, not a reference system. Its '
            't_sing is the solver termination time -- '
            f"{100 * sp.get('frac_density_criterion', float('nan')):.0f}% by "
            'the density criterion and '
            f"{100 * sp.get('frac_knudsen_floor', float('nan')):.0f}% by the "
            'Knudsen fluid-validity floor -- so phi does not run over a common '
            'interval and the system must not be used to calibrate a new '
            "system's numbers."),
        'verdict': (
            'every reference system honours its stated event rule' if not bad
            else 'the stated event rule does NOT describe '
                 + ', '.join(sorted(bad))),
        '_provenance': stamp('sc_event_spec.py'),
    }
    path = os.path.join(OUT, 'event_spec.json')
    json.dump(out, open(path, 'w'), indent=1)

    print(f"{'system':9s} {'spec f':>8s} {'median':>9s} {'min':>9s} "
          f"{'max':>9s} {'within 1%':>10s}  phi endpoint spread")
    for k in list(SPEC_F) + ['sidm']:
        if k not in out:
            continue
        v = out[k]
        print(f"{k:9s} {v['specified_f']:8.0f} {v['ratio_median']:9.2f} "
              f"{v['ratio_min']:9.2f} {v['ratio_max']:9.2f} "
              f"{100 * v['frac_within_1pct_of_f']:9.1f}%  "
              f"{v['phi_endpoint_spread_dex']:.3f} dex")
    print('\n' + out['_summary']['verdict'])
    print('\n' + out['_summary']['sidm_note'])
    print('wrote', path)


if __name__ == '__main__':
    main()
